#!/usr/bin/env python3
"""Inventory documented declarations; does not infer implemented ABI parity."""
import argparse
from dataclasses import dataclass
from pathlib import Path
import re


@dataclass
class Contract:
    service: str
    line: int
    declaration: str
    guards: tuple
    version_note: str


def contracts(text, native):
    # Keep line positions while stripping comments, without damaging quoted
    # defaults that contain comment markers.
    tokens = r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/'
    code = re.sub(tokens, lambda match: re.sub(r'[^\n]', ' ', match[0])
                  if match[0].startswith(('//', '/*')) else match[0], text)
    original = text.splitlines()
    guards = []
    service = None
    note = ''
    pending = []
    first_line = 0
    for number, line in enumerate(code.splitlines(), 1):
        raw = original[number - 1].strip()
        if raw.startswith('//') and ('Available only in API version' in raw or
                                      'new functions in T2' in raw):
            note = f'{number}: {raw[2:].strip()}'
        stripped = line.strip()
        directive = re.match(r'#(if|ifdef|ifndef|elif|else|endif)\b(.*)', stripped)
        if directive:
            kind, condition = directive.groups()
            if kind in {'if', 'ifdef', 'ifndef'}:
                guards.append([stripped])
            elif not guards:
                raise ValueError(f'line {number}: unmatched #{kind}')
            elif kind == 'endif':
                guards.pop()
            else:
                # Retain the branch history literally; do not guess a C
                # preprocessor expression or discard preceding elif branches.
                guards[-1].append(stripped)
            continue
        declaration_service = re.match(r'DECLARE_SCRIPT_SERVICE\((\w+),', stripped)
        if native and declaration_service:
            service = declaration_service[1]
        elif not native and re.fullmatch(r'[A-Z][A-Za-z0-9_]*', stripped):
            service = stripped
        if stripped.startswith('}'):
            service = None
            note = ''
        if not service:
            continue
        starts_method = (re.match(r'STDMETHOD(?:_|\s*\()', stripped) if native else
                         re.match(r'(?:[\w:&<>]+\s+)?\w+\(', stripped))
        if not pending and not starts_method:
            continue
        if not pending:
            first_line = number
        pending.append(stripped)
        if ';' in stripped:
            yield Contract(service, first_line, ' '.join(pending),
                           tuple(' -> '.join(branch) for branch in guards), note)
            pending = []
    if pending:
        raise ValueError(f'line {first_line}: unterminated declaration')
    if guards:
        raise ValueError('unterminated preprocessor guard')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('game', type=Path)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    files = [(path, True) for path in sorted((args.game / 'DOC/script').glob('*.txt'))]
    files.append((args.game / 'DOC/squirrel_script/API-reference_services.txt', False))
    rows = []
    for path, native in files:
        for item in contracts(path.read_text(errors='replace'), native):
            values = (f'`{path.relative_to(args.game)}:{item.line}`', item.service,
                      f'`{item.declaration}`', '; '.join(item.guards) or '—',
                      item.version_note or 'No local version annotation')
            rows.append('| ' + ' | '.join(value.replace('|', '\\|') for value in values) + ' |')
    intro = ['# Documented script declarations', '',
             'Generated by `tools/compatibility_audit/script_contracts.py`.', '',
             'This supplements the method-name compatibility matrix. Every overload and',
             'conditional declaration is retained. Guards show literal branch history;',
             'version notes are nearby documentation annotations, not evaluated availability.',
             'No row establishes implemented vtable order, version gating or runtime parity.', '',
             '| Reference | Service | Declaration | Conditional branch history | Version note |',
             '| --- | --- | --- | --- | --- |']
    args.output.write_text('\n'.join(intro + rows + ['', f'Declarations: {len(rows)}.', '']))
    print(f'Wrote {len(rows)} declarations to {args.output}')


if __name__ == '__main__':
    main()
