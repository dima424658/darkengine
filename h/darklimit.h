/*
 * Central compatibility-limit inventory.
 *
 * LEGACY describes the original TDP/Gold/Thief II representation.  NEWDARK
 * describes the extended representation documented by NewDark 1.28.  Runtime
 * capacities use the broadest supported representation and must not be
 * reduced merely because the current content profile is a retail game.
 *
 * Codec validation and writers should use the explicit format constants near
 * the bottom of this file.  Runtime arrays should use DARK_LIMIT_RUNTIME_*.
 */

