/* Keep the derived capacities honest when this inventory is updated. */
#if DARK_LIMIT_LEGACY_TOTAL_LIGHT_SLOTS != \
      (DARK_LIMIT_LEGACY_STATIC_LIGHTS + DARK_LIMIT_LEGACY_DYNAMIC_LIGHTS)
#error Legacy light capacity is inconsistent
#endif
#if DARK_LIMIT_NEWDARK_TOTAL_LIGHT_SLOTS != \
      (DARK_LIMIT_NEWDARK_STATIC_LIGHTS + DARK_LIMIT_NEWDARK_DYNAMIC_LIGHTS)
#error NewDark light capacity is inconsistent
#endif
#if DARK_LIMIT_RUNTIME_TERRAIN_TEXTURES != \
      (DARK_LIMIT_WREXT_TEXTURE_ID_MAX + 1)
#error Runtime terrain texture capacity cannot represent the WREXT range
#endif
#if DARK_LIMIT_RUNTIME_AIPATH_INDEX < DARK_LIMIT_AIPATH_34_INDEX
#error Runtime AI path capacity cannot represent AIPATH 3.4
#endif

